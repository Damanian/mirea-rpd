def main():
    path = Path(__file__).with_name("schematics-autofill.json")
    model = json.loads(path.read_text(encoding="utf-8"))
    model["defer_approval"] = True  # The user explicitly requested leaving these fields empty.
    model["description"] = (
        "Исправленный пример: подробные занятия с пределами 2/4/2/4 ч.; 90 заданий ФОС по правилам презентации 25.06.2026. Утверждение отложено пользователем."
    )
    for outcome in model["learning_outcomes"]:
        for key in list(outcome):
            if key.startswith(("current_", "intermediate_", "mark")) or key == "rating_scale":
                del outcome[key]
        bank = BANKS[(outcome["indicator"], outcome["category"])]
        assert len(bank) == 15
        outcome["current_tasks"], outcome["intermediate_tasks"] = bank[:5], bank[5:]
        outcome["competency_description"] = (
            "Способен понимать принципы работы современных информационных технологий и программных средств, в том числе отечественного производства, и использовать их при решении задач профессиональной деятельности"
        )
    for index, (section, content) in enumerate(zip(model["sections"], CONTENT, strict=True)):
        lectures, lab, practices, self_study = content
        semester = 5 if index < 4 else 6
        works = []
        for wtype, hours, values in [(1, 2, lectures), (2, 4, [lab]), (3, 2, practices)]:
            for name, detail in values:
                work = {
                    "name": name,
                    "wtype": wtype,
                    "hours": hours,
                    "semester": semester,
                    "comment": detail,
                    "indicators": ["ОПК-2.1", "ОПК-2.2"],
                }
                if wtype == 3:
                    work["activity_id"] = 72
                works.append(work)
        for hours, name, detail in self_study:
            works.append(
                {
                    "name": name,
                    "wtype": 4,
                    "hours": hours,
                    "semester": semester,
                    "comment": detail,
                    "activity_id": 73,
                    "indicators": ["ОПК-2.1", "ОПК-2.2"],
                }
            )
        section["works"] = works
        section["comment"] = " ".join(detail for _, detail in lectures)
    questions = []
    for section in model["sections"]:
        for work in section["works"]:
            if work["wtype"] == 1:
                questions.append(f"{len(questions) + 1}. {work['name']}. {work['comment']}")
    model["fos"]["questions"] = "\n".join(questions)
    path.write_text(json.dumps(model, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
